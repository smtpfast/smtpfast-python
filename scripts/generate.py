"""Build the Python SDK from spec/openapi.json. No dependencies beyond the standard library.

Writes two files that are never edited by hand:
  src/smtpfast/types.py       a TypedDict for every request and response shape
  src/smtpfast/_resources.py  client.emails.send() and the other methods, sync and async,
                              named from the x-sdk-group and x-sdk-method of each operation
"""
from __future__ import annotations

import json
import keyword
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "spec/openapi.json").read_text())
SCHEMAS = SPEC["components"]["schemas"]
METHODS = ["get", "post", "put", "patch", "delete"]
HEADER = "# Generated by scripts/generate.py from spec/openapi.json. Do not edit.\n"


def pascal(s: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", s)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def snake(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9]+", "_", s)
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", s).lower().strip("_")


def ident(s: str) -> str:
    s = snake(s)
    return s + "_" if keyword.iskeyword(s) or s in {"options", "self", "params"} else s


def deref(schema):
    while isinstance(schema, dict) and "$ref" in schema:
        schema = SCHEMAS[schema["$ref"].split("/")[-1]]
    return schema


# --- types.py -------------------------------------------------------------

class Types:
    def __init__(self):
        self.defs: dict[str, str] = {}   # name -> definition source
        self.deps: dict[str, set[str]] = {}
        self.aliases: set[str] = set()

    def expr(self, schema, hint: str, deps: set[str]) -> str:
        """The Python type for a schema; inline objects become named TypedDicts."""
        if schema is None or schema is True or schema == {}:
            return "Any"
        if "$ref" in schema:
            name = pascal(schema["$ref"].split("/")[-1])
            deps.add(name)
            return name
        for key in ("anyOf", "oneOf"):
            if key in schema:
                members = [self.expr(s, f"{hint}{i + 1}" if len(schema[key]) > 1 else hint, deps) for i, s in enumerate(schema[key])]
                return union(members)
        if "allOf" in schema:
            if len(schema["allOf"]) == 1 and not schema.get("properties"):
                return self.expr(schema["allOf"][0], hint, deps)
            merged = {"type": "object", "properties": {}, "required": []}
            for part in schema["allOf"] + [schema]:
                part = deref(part)
                merged["properties"].update(part.get("properties", {}))
                merged["required"] += part.get("required", [])
            return self.expr(merged, hint, deps)
        types = schema.get("type")
        types = types if isinstance(types, list) else [types] if types else []
        nullable = "null" in types
        types = [t for t in types if t != "null"]
        if nullable and not types and not any(k in schema for k in ("enum", "properties", "items", "additionalProperties")):
            return "None"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            nullable = nullable or None in schema["enum"]
            out = f"Literal[{', '.join(json.dumps(v) for v in values)}]" if values else "None"
        elif len(types) > 1:
            out = union([self.expr({**schema, "type": t}, hint, deps) for t in types])
        elif not types:
            out = self.object(schema, hint, deps) if "properties" in schema else "Any"
        else:
            t = types[0]
            if t == "string":
                out = "str"
            elif t == "integer":
                out = "int"
            elif t == "number":
                out = "float"
            elif t == "boolean":
                out = "bool"
            elif t == "array":
                out = f"list[{self.expr(schema.get('items'), hint + 'Item', deps)}]"
            else:
                out = self.object(schema, hint, deps)
        return union([out, "None"]) if nullable else out

    def object(self, schema, hint: str, deps: set[str]) -> str:
        props = schema.get("properties")
        if not props:
            extra = schema.get("additionalProperties")
            value = self.expr(extra, hint + "Value", deps) if isinstance(extra, dict) else "Any"
            return f"dict[str, {value}]"
        self.define(hint, schema)
        deps.add(hint)
        return hint

    def define(self, name: str, schema) -> None:
        if name in self.defs:
            return
        self.defs[name] = ""  # reserve, for recursive shapes
        deps: set[str] = set()
        required = set(schema.get("required", []))
        fields = []
        for key, prop in schema.get("properties", {}).items():
            t = self.expr(prop, name + pascal(key), deps)
            fields.append(f"        {json.dumps(key)}: {t if key in required else f'NotRequired[{t}]'},")
        doc = schema.get("description")
        comment = f"# {doc.splitlines()[0][:150]}\n" if doc else ""
        self.defs[name] = f'{comment}{name} = TypedDict(\n    "{name}",\n    {{\n' + "\n".join(fields) + "\n    },\n)\n"
        self.deps[name] = deps - {name}

    def alias(self, name: str, schema) -> str:
        """A named type for a top-level schema that is not an object, such as a list."""
        deps: set[str] = set()
        target = self.expr(schema, name + "Item" if deref(schema).get("type") == "array" else name, deps)
        if target == name:
            return name
        self.defs[name] = f"{name}: TypeAlias = {target}\n"
        self.deps[name] = deps - {name}
        return name

    def source(self) -> str:
        out, done = [], set()

        def visit(n, stack=()):
            if n in done or n in stack or n not in self.defs:
                return
            for d in sorted(self.deps.get(n, ())):
                visit(d, stack + (n,))
            done.add(n)
            out.append(self.defs[n])

        for n in self.defs:
            visit(n)
        return (
            HEADER
            + '"""Request and response shapes of the SMTPfast API, as TypedDicts: plain dicts at runtime."""\n'
            + "from __future__ import annotations\n\n"
            + "from typing import Any, Literal, Union\n\n"
            + "from typing_extensions import NotRequired, TypeAlias, TypedDict\n\n\n"
            + "\n\n".join(out)
        )


def union(members: list[str]) -> str:
    seen = []
    for m in members:
        for part in split_union(m):
            if part not in seen:
                seen.append(part)
    if len(seen) == 1:
        return seen[0]
    if "Any" in seen:
        return "Any"
    return "Union[" + ", ".join(seen) + "]"


def split_union(t: str) -> list[str]:
    if not t.startswith("Union["):
        return [t]
    inner, depth, parts, cur = t[6:-1], 0, [], ""
    for ch in inner:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    return parts


types = Types()
for name, schema in SCHEMAS.items():
    types.alias(pascal(name), schema)

# --- operations -------------------------------------------------------------

ops = []
for path, item in SPEC["paths"].items():
    for method in METHODS:
        op = item.get(method)
        if not op:
            continue
        if "x-sdk-group" not in op or "x-sdk-method" not in op:
            raise SystemExit(f"{op['operationId']} has no x-sdk-group/x-sdk-method")
        params = op.get("parameters", [])
        name = pascal(op["operationId"])
        body_schema = (op.get("requestBody") or {}).get("content", {}).get("application/json", {}).get("schema")
        body_type = None
        if body_schema is not None:
            body_type = types.alias(name + "Params", body_schema) if "$ref" not in body_schema else pascal(body_schema["$ref"].split("/")[-1])
        result_type = "Any"
        for code, res in op.get("responses", {}).items():
            if code.startswith("2"):
                schema = (res.get("content") or {}).get("application/json", {}).get("schema")
                if schema is not None:
                    result_type = pascal(schema["$ref"].split("/")[-1]) if "$ref" in schema else types.alias(name + "Response", schema)
                break
        query = []
        for p in params:
            if p["in"] != "query":
                continue
            d: set[str] = set()
            query.append((p["name"], ident(p["name"]), types.expr(p.get("schema"), name + pascal(p["name"]), d), p.get("required", False)))
        result = deref(SCHEMAS.get(result_type)) if result_type in SCHEMAS else None
        ops.append({
            "group": op["x-sdk-group"],
            "method": snake(op["x-sdk-method"]),
            "http": method.upper(),
            "path": path,
            "summary": op.get("summary", op["operationId"]),
            "path_params": re.findall(r"\{(\w+)\}", path),
            "query": query,
            "body": body_type,
            "body_required": bool((op.get("requestBody") or {}).get("required")),
            "result": result_type,
            "idempotent": any(p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in params),
            "paginated": method == "get" and any(q[0] == "after" for q in query),
            # The typed method parses JSON, so it asks for JSON when the default format is something else.
            "json_format": any(
                p["in"] == "query" and p["name"] == "format" and "json" in (p.get("schema") or {}).get("enum", [])
                and (p.get("schema") or {}).get("default") != "json"
                for p in params
            ),
        })

# A list pages with a cursor when its answer has data[] and has_more.
for op in ops:
    if op["paginated"]:
        res = next(
            (v for k, v in SPEC["paths"][op["path"]]["get"]["responses"].items() if k.startswith("2")), {}
        )
        schema = deref((res.get("content") or {}).get("application/json", {}).get("schema") or {})
        data = deref((schema.get("properties") or {}).get("data") or {})
        op["paginated"] = data.get("type") == "array" and "has_more" in (schema.get("properties") or {})
        items = data.get("items") or {}
        op["item"] = pascal(items["$ref"].split("/")[-1]) if "$ref" in items else "Any"


# --- _resources.py -----------------------------------------------------------

def tree():
    root = {"groups": {}, "ops": []}
    for op in ops:
        node = root
        for g in op["group"]:
            node = node["groups"].setdefault(g, {"groups": {}, "ops": []})
        node["ops"].append(op)
    return root


def signature(op, with_body=True):
    """with_body=False is the list_all variant: no body, and no page or before, which it manages."""
    args = ["self"] + [f"{ident(p)}: str" for p in op["path_params"]]
    if with_body and op["body"]:
        args.append(f"params: {op['body']}" if op["body_required"] else f"params: {op['body']} | None = None")
    kw = []
    for name, py, t, required in op["query"]:
        if not with_body and name in ("page", "before", "latest"):
            continue
        kw.append(f"{py}: {t}" if required else f"{py}: {t} | None = None")
    if op["idempotent"]:
        kw.append("idempotency_key: str | None = None")
    kw.append("options: RequestOptions | None = None")
    return re.sub(r"\blist\[", "builtins.list[", ", ".join(args + ["*"] + kw))


def call_args(op, with_body=True):
    path_args = ", ".join(f'"{p}": {ident(p)}' for p in op["path_params"])
    query = ", ".join(
        f'"{name}": {py} if {py} is not None else "json"' if name == "format" and op.get("json_format") else f'"{name}": {py}'
        for name, py, _, _ in op["query"]
        if with_body or name not in ("page", "before", "latest")
    )
    parts = [f'"{op["http"]}"', f'"{op["path"]}"', f"path_params={{{path_args}}}" if path_args else "path_params=None"]
    parts.append(f"query={{{query}}}" if query else "query=None")
    parts.append("body=params" if with_body and op["body"] else "body=None")
    if op["idempotent"]:
        parts.append("idempotent=True, idempotency_key=idempotency_key")
    parts.append("options=options")
    return ", ".join(parts)


def emit_class(node, prefix: list[str], is_async: bool, classes: list[str]) -> str:
    cls = ("Async" if is_async else "") + "".join(pascal(p) for p in prefix) + "Resource"
    lines = [f"class {cls}(_{'Async' if is_async else 'Sync'}Resource):"]
    if prefix:
        lines.append(f'    """`client.{".".join(snake(p) for p in prefix)}`"""')
    children = []
    for name, child in node["groups"].items():
        child_cls = emit_class(child, prefix + [name], is_async, classes)
        children.append((snake(name), child_cls))
    if children:
        lines.append("")
        lines.append("    def __init__(self, core: Any) -> None:")
        lines.append("        super().__init__(core)")
        for attr, child_cls in children:
            lines.append(f"        self.{attr} = {child_cls}(core)")
    for op in node["ops"]:
        aw = "await " if is_async else ""
        lines.append("")
        result = re.sub(r"\blist\[", "builtins.list[", op["result"])
        lines.append(f"    {'async ' if is_async else ''}def {op['method']}({signature(op)}) -> {result}:")
        lines.append(f'        """{op["summary"].rstrip(".")}. `{op["http"]} {op["path"]}`"""')
        lines.append(f"        return {aw}self._core.request({call_args(op)})  # type: ignore[no-any-return]")
        if op["paginated"]:
            iterator = f"AsyncIterator[{op['item']}]" if is_async else f"Iterator[{op['item']}]"
            lines.append("")
            lines.append(f"    def {op['method']}_all({signature(op, with_body=False)}) -> {iterator}:")
            lines.append(f'        """Every item of {op["method"]}, fetching the following pages as you iterate."""')
            lines.append(f"        return self._core.paginate({call_args(op, with_body=False)})")
    classes.append("\n".join(lines) + "\n")
    return cls


classes: list[str] = []
root = tree()
emit_class(root, [], False, classes)
emit_class(root, [], True, classes)
resources = (
    HEADER
    + "from __future__ import annotations\n\n"
    + "import builtins\n"
    + "from typing import Any, AsyncIterator, Iterator, Literal, Union\n\n"
    + "from ._core import RequestOptions, _AsyncResource, _SyncResource\n"
    + "from .types import *  # noqa: F403\n\n\n"
    + "\n\n".join(classes)
)
(ROOT / "src/smtpfast/types.py").write_text(types.source())
(ROOT / "src/smtpfast/_resources.py").write_text(resources)
print(f"src/smtpfast/types.py: {len(types.defs)} types; src/smtpfast/_resources.py: {len(ops)} operations")
